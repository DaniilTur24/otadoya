-- Один сотрудник — одна смена в день. Проверка validateUniqueShift в приложении — это
-- findFirst без блокировки: два одновременных POST (двойной клик, ретрай на плохой связи) оба
-- проходили и создавали две оплачиваемые смены (QA раунд 3, №3; раунд 4, №7).
-- Частичный индекс: записи без смены (shift_type IS NULL) — например, чистая выручка без
-- привязки к сотруднику-кассиру — по-прежнему могут повторяться в один день, а отклонённые
-- (устаревший статус) не должны «занимать» день.
-- Prisma не умеет объявлять частичные уникальные индексы в schema.prisma, поэтому индекс живёт
-- только здесь; приложение ловит P2002 на insert/update и отвечает 409.
CREATE UNIQUE INDEX "daily_revenue_entries_employee_shift_day_key"
  ON "daily_revenue_entries" ("employee_id", "date")
  WHERE "shift_type" IS NOT NULL AND "status" <> 'rejected';
