/**
 * Минимальный номинал наличных в Казахстане — 5 тенге (монеты 5/10 тг). Любая денежная сумма,
 * вычисленная делением/процентом (оклад за смену, премия за выручку, лестничная премия), должна
 * округляться до кратного 5 — иначе получается невыплатимая сумма вроде 46666.67 ₸, и итог
 * зависит от порядка суммирования слагаемых (float-арифметика).
 *
 * НЕ применять к суммам, введённым человеком напрямую (аванс, доплата, бонус, выручка, оклад в
 * настройках сотрудника) — это факты о реальных деньгах, округление исказило бы то, что
 * бухгалтер реально ввёл. Применять только к результатам вычислений. Итог к выплате — тоже
 * результат вычисления: он округляется один раз в конце, поэтому строки в карточке сотрудника
 * могут отличаться от итога на 1–2 ₸.
 */
export function roundMoney(value: number): number {
  // + 0 превращает −0 в 0: маленький аванс без начислений иначе показался бы как «-0 ₸»
  return Math.round(value / 5) * 5 + 0;
}
