const MAX_PATTERN_LENGTH = 300;

// Ловит самый частый источник ReDoS (catastrophic backtracking) — квантификатор над группой,
// которая сама содержит квантификатор, например (a+)+, (\d*)+, ([^,]+)*. Это эвристика, а не
// полный анализ регулярного выражения: она не поймает все катастрофические паттерны (например
// пересекающуюся альтернацию вроде (a|a)*), но закрывает подавляющее большинство случайных
// ошибок при написании правил.
const NESTED_QUANTIFIER = /\([^()]*[+*][^()]*\)[+*]/;

/** Возвращает причину, почему паттерн небезопасен, или null если явных проблем не найдено. */
export function unsafeRegexReason(pattern: string): string | null {
  if (pattern.length > MAX_PATTERN_LENGTH) {
    return `Регулярное выражение слишком длинное (максимум ${MAX_PATTERN_LENGTH} символов)`;
  }
  if (NESTED_QUANTIFIER.test(pattern)) {
    return 'Регулярное выражение содержит вложенные повторения (например (a+)+) — это может вызвать зависание сервера на определённых строках';
  }
  return null;
}
